# Documentation: https://docs.python.org/3/library/stdtypes.html#truth-value-testing
# bool("") is False - empty string is considered False
print(f'bool("") is {bool("")}')
# bool("0") is True - any non-empty string is True, even "0"
print(f'bool("0") is {bool("0")}')
# bool(0) is False - number 0 is False
print(f"bool(0) is {bool(0)}")
# bool(0.0) is False - 0.0 is also False
print(f"bool(0.0) is {bool(0.0)}")
# bool("False") is True - non-empty string is True, text doesn't matter
print(f'bool("False") is {bool("False")}')
